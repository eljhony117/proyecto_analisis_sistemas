        CHECK (UPPER(ESTADO_AUTORIZACION) IN ('AUTORIZADO','ACTIVO','INACTIVO'))
);

/*Restricciones de la tabla miembros del comite que se hace por medio de un triger*/
CREATE OR REPLACE TRIGGER trg_valida_miembro_autorizado
BEFORE INSERT OR UPDATE ON MIEMBRO_COMITE
FOR EACH ROW
BEGIN
    IF UPPER(:NEW.estado_autorizacion) NOT IN ('AUTORIZADO', 'ACTIVO')
       OR :NEW.es_evaluador = 'N' THEN
 
        RAISE_APPLICATION_ERROR(
            -20030,
            'Acceso denegado: El docente (ID: ' || :NEW.id_docente || ') no está autorizado para realizar evaluaciones.'
        );
 
    END IF;
END;

