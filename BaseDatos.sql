-- Tabla de historial de estado
CREATE TABLE HISTORIAL_ESTADO (
    ID_HISTORIAL NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_SOLICITUD NUMBER NOT NULL,
    FECHA_CAMBIO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ESTADO_ANTERIOR VARCHAR2(50) NOT NULL,
    ESTADO_NUEVO VARCHAR2(50) NOT NULL,
 
    CONSTRAINT FK_HIST_SOLICITUD
        FOREIGN KEY (ID_SOLICITUD) REFERENCES SOLICITUD_BECAS(ID_SOLICITUD),
        
    CONSTRAINT CK_HIST_ESTADO_ANT
        CHECK (UPPER(ESTADO_ANTERIOR) IN ('PENDIENTE','EN_REVISION','APROBADA','RECHAZADA')),
        
    CONSTRAINT CK_HIST_ESTADO_NUE
        CHECK (UPPER(ESTADO_NUEVO) IN ('PENDIENTE','EN_REVISION','APROBADA','RECHAZADA')),
    
    CONSTRAINT CK_HIST_ESTADO_DIF
        CHECK (UPPER(ESTADO_ANTERIOR) <> UPPER(ESTADO_NUEVO))
);
 
/*Restriccion de trigger para la tabla historial de estado que nos permite registrar cualuier cambio en el estado de una solicitud de beca*/
CREATE OR REPLACE TRIGGER TRG_AUDITA_ESTADO_SOLICITUD
AFTER UPDATE OF ESTADO_SOLICITUD ON SOLICITUD_BECAS
FOR EACH ROW
BEGIN
    IF :OLD.ESTADO_SOLICITUD <> :NEW.ESTADO_SOLICITUD THEN
        INSERT INTO HISTORIAL_ESTADO (
            ID_SOLICITUD, ESTADO_ANTERIOR, ESTADO_NUEVO, FECHA_CAMBIO
        ) VALUES (
            :OLD.ID_SOLICITUD, :OLD.ESTADO_SOLICITUD, :NEW.ESTADO_SOLICITUD, SYSDATE
        );
    END IF;
END;

SELECT * FROM HISTORIAL_ESTADO;
