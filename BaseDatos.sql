/*Restricciones que se realizan dentro de un trigger*/
CREATE OR REPLACE TRIGGER trg_valida_pasword_usuario
BEFORE INSERT OR UPDATE OF Contrasena ON USUARIO
FOR EACH ROW
DECLARE
    v_Contrasena VARCHAR2(100);
BEGIN
    v_Contrasena := :NEW.Contrasena;
 
    IF LENGTH(v_Contrasena) < 8 OR LENGTH(v_Contrasena) > 18 THEN
        RAISE_APPLICATION_ERROR(-20001, 'La contraseña debe tener entre 8 y 18 caracteres');
    END IF;
 
    IF NOT REGEXP_LIKE(v_Contrasena, '[A-Z]') THEN
        RAISE_APPLICATION_ERROR(-20001, 'La contraseña debe tener al menos una letra mayuscula');
    END IF;
 
    IF NOT REGEXP_LIKE(v_Contrasena, '[a-z]') THEN
        RAISE_APPLICATION_ERROR(-20001, 'La contraseña debe tener al menos una letra minuscula');
    END IF;
 
    IF NOT REGEXP_LIKE(v_Contrasena, '[0-9]') THEN
        RAISE_APPLICATION_ERROR(-20001, 'La contraseña debe tener al menos un numero');
    END IF;
 
    IF NOT REGEXP_LIKE(v_Contrasena, '[!@#$%^&*()_+\-=\[\]{};'':"\\|,.<>\/?]') THEN
        RAISE_APPLICATION_ERROR(-20001, 'La contraseña debe tener al menos un caracter especial');
    END IF;
END;  

