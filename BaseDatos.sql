    ID_SOLICITUD NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_ESTUDAINTE NUMBER NOT NULL,
    ID_CONVOCATORIA NUMBER NOT NULL,
    ESTADO_SOLICITUD VARCHAR2(20) NOT NULL,
