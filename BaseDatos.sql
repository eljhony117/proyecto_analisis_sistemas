CREATE OR REPLACE TRIGGER TRG_AUDITA_ESTADO_SOLICITUD
AFTER UPDATE OF ESTADO_SOLICITUD ON SOLICITUD_BECAS
FOR EACH ROW
BEGIN
    IF :OLD.ESTADO_SOLICITUD <> :NEW.ESTADO_SOLICITUD THEN
        INSERT INTO HISTORIAL_ESTADO (
            ID_SOLICITUD, ESTADO_ANTERIOR, ESTADO_NUEVO, FECHA_CAMBIO
        ) VALUES (
            :OLD.ID_SOLICITUD, :OLD.ESTADO_SOLICITUD, :NEW.ESTADO_SOLICITUD, SYSDATE
        );
    END IF;
END;