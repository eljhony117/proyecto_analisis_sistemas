-- TABLA ESTUDIANTE
CREATE TABLE ESTUDIANTE (
    ID_ESTUDIANTE NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(50) NOT NULL,
    APELLIDO VARCHAR2(50) NOT NULL,
    DPI VARCHAR2(13) UNIQUE NOT NULL,
    CORREO VARCHAR2(100) UNIQUE NOT NULL,
    FECHA_NACIMIENTO DATE NOT NULL,
    NIVEL_EDUCATIVO VARCHAR2(20) NOT NULL,

    CONSTRAINT CK_EST_NOMBRE
        CHECK (REGEXP_LIKE(NOMBRE,'^[A-Za-zÁÉÍÓÚáéíóúÑñ ]+$')),

    CONSTRAINT CK_EST_APELLIDO
        CHECK (REGEXP_LIKE(APELLIDO,'^[A-Za-zÁÉÍÓÚáéíóúÑñ ]+$')),

    CONSTRAINT CK_EST_NIVEL
        CHECK (UPPER(NIVEL_EDUCATIVO) IN ('MEDIO', 'UNIVERSITARIO', 'POSGRADO'))
);

/*LAS RESTRICCIONES QUE FALTARON PERO AGREGO PARA LA TABLA ESTUDIANTE SON;
1. VALIDAR QUE DPI TENGA EXACTAMENTE 13 DÍGITOS*/
ALTER TABLE ESTUDIANTE
ADD CONSTRAINT CK_EST_DPI
CHECK (REGEXP_LIKE(DPI, '^[0-9]{13}$'));

