    ESTADO_AUTORIZACION VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
 
    CONSTRAINT PK_MIEMBRO_COMITE
        PRIMARY KEY (ID_COMITE, ID_DOCENTE),
 
    CONSTRAINT FK_MIEMBRO_COMITE
        FOREIGN KEY (ID_COMITE) REFERENCES COMITE(ID_COMITE),
 
