    CONSTRAINT FK_SOL_ESTUDIANTE
        FOREIGN KEY (ID_ESTUDAINTE) REFERENCES ESTUDIANTE(ID_ESTUDAINTE),
 
    CONSTRAINT FK_SOL_CONVOCATORIA
        FOREIGN KEY (ID_CONVOCATORIA) REFERENCES CONVOCATORIA(ID_CONVOCATORIA),
 
    CONSTRAINT CK_SOL_ESTADO
        CHECK (UPPER(ESTADO_SOLICITUD) IN ('PENDIENTE', 'EN_REVISION', 'APROBADA', 'RECHAZADA')),
 
    CONSTRAINT UQ_SOL_EST_CONV
        UNIQUE (ID_ESTUDAINTE, ID_CONVOCATORIA)
);

/*Restricciones que se realiza con trigger*/
CREATE OR REPLACE TRIGGER trg_valida_estado_convocatoria_becas
BEFORE INSERT ON SOLICITUD_BECAS
FOR EACH ROW
DECLARE
    v_estado CONVOCATORIA.ESTADO%TYPE;
BEGIN
    SELECT estado
      INTO v_estado
      FROM CONVOCATORIA
     WHERE id_convocatoria = :NEW.id_convocatoria;
 
    IF UPPER(v_estado) IN ('CERRADO', 'CANCELADO') THEN
        RAISE_APPLICATION_ERROR(
            -20020,
            'No se puede ingresar la solicitud. La convocatoria está ' || v_estado || '.'
        );
    END IF;
 
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(
            -20021,
            'La convocatoria asociada (ID: ' || :NEW.id_convocatoria || ') no existe.'
        );
END;

SELECT * FROM SOLICITUD_BECAS;

